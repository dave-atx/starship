#!/usr/bin/env bash
# Install the forked starship (dave-atx/starship, branch `dave`) as the Claude Code
# statusline, replacing cship. The shell prompt keeps using the existing starship.
#
# `dave` = starship/starship#7442 (claude_usage, pavi2410's branch)
#        + #7822 ($*_reset_at) + #7821 (claude_model effort_styles)
#
# Run it on a new machine, or again after the branch moves:
#   curl -fsSL https://raw.githubusercontent.com/dave-atx/starship/dave/contrib/install-claude-statusline.sh | bash
#
#   1. Builds the fork into ~/.local/starship-fork (off PATH)
#   2. Writes ~/.config/starship-claude.toml = your starship.toml + the Claude section
#   3. Points statusLine in ~/.claude/settings.json at it (backs up the file first)
#
# Safe to re-run: it rebuilds the binary and regenerates the config each time.
set -euo pipefail

FORK_ROOT="$HOME/.local/starship-fork"
FORK_BIN="$FORK_ROOT/bin/starship"
BASE_CONFIG="${STARSHIP_CONFIG:-$HOME/.config/starship.toml}"
CLAUDE_CONFIG="$HOME/.config/starship-claude.toml"
SETTINGS="$HOME/.claude/settings.json"

say() { printf '\n==> %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

# ── Preflight ──────────────────────────────────────────────────────────────────
command -v cargo >/dev/null || die "cargo not found. Install Rust first: https://rustup.rs (then open a new shell)"
command -v git >/dev/null || die "git not found"
[ -f "$BASE_CONFIG" ] || die "no starship config at $BASE_CONFIG"
[ -f "$SETTINGS" ] || die "no Claude Code settings at $SETTINGS"
if grep -qE '^\[(profiles|claude_[a-z_]+)(\]|\.)' "$BASE_CONFIG"; then
  die "$BASE_CONFIG already has [profiles] or [claude_*] tables; merging would duplicate them. Remove them or merge by hand."
fi
if command -v jq >/dev/null; then JSON_TOOL=jq
elif command -v python3 >/dev/null && python3 -c 'import json' 2>/dev/null; then JSON_TOOL=python3
else die "need jq or python3 to edit $SETTINGS"
fi

# ── 1. Build the fork ──────────────────────────────────────────────────────────
say "Building dave-atx/starship@dave into $FORK_ROOT (takes a few minutes)"
cargo install --locked --force --git https://github.com/dave-atx/starship --branch dave --root "$FORK_ROOT"
"$FORK_BIN" --version | head -2

# ── 2. Statusline config ───────────────────────────────────────────────────────
say "Writing $CLAUDE_CONFIG"
{
  echo "# Claude Code statusline config for the forked starship ($FORK_ROOT)."
  echo "# Generated by install script: $BASE_CONFIG + the Claude section below."
  echo "# Kept separate because stock starship warns about the unknown claude_usage /"
  echo "# effort_styles keys. Re-run the script after changing $BASE_CONFIG."
  echo
  echo "# No blank line above the statusline"
  echo "add_newline = false"
  echo
  # Drop any add_newline from the base config so the key isn't defined twice
  grep -v '^[[:space:]]*add_newline[[:space:]]*=' "$BASE_CONFIG"
  echo
  cat <<'CLAUDE_SECTION'
# ── Claude Code statusline (`starship statusline claude-code`) ────────────────
# Line 1 mirrors the shell prompt; line 2 replaces cship's model / effort / context / usage line
[profiles]
claude-code = """
$hostname\
$env_var\
$custom\
$directory\
$git_branch\
$git_status\
[ ](prev_bg)\
$line_break\
$claude_model\
$claude_context\
$claude_usage"""

[claude_model]
format = "[$symbol$model]($style)( [⚡ $effort]($effort_style)) "
symbol = "🤖 "
style = "bold cyan"

[claude_model.effort_styles]
low = "fg:#7dcfff"
medium = "fg:#7dcfff"
high = "fg:#e0af68"
xhigh = "bold fg:#e0af68"
max = "bold fg:#f7768e"

[claude_context]
format = "[$gauge $percentage]($style) "
gauge_width = 10
gauge_partial_symbol = ""

[[claude_context.display]]
threshold = 0
style = ""

[[claude_context.display]]
threshold = 40
style = "yellow"

[[claude_context.display]]
threshold = 70
style = "bold red"

# Both windows share one $style, picked by the busier one. A window that is
# missing or already reset drops its group.
[claude_usage]
format = "[(⌛ 5h $five_hour_percentage \\($five_hour_reset_at\\))( 📅 7d $seven_day_percentage \\($seven_day_reset_at\\))]($style)"
reset_time_format = "%-I:%M %p"
reset_date_time_format = "%a %-I:%M %p"

[[claude_usage.display]]
threshold = 0
style = "green"

[[claude_usage.display]]
threshold = 60
style = "yellow"

[[claude_usage.display]]
threshold = 80
style = "bold red"
CLAUDE_SECTION
} > "$CLAUDE_CONFIG"

# ── 3. Point Claude Code at it ─────────────────────────────────────────────────
STATUS_CMD="STARSHIP_CONFIG=$CLAUDE_CONFIG $FORK_BIN statusline claude-code"
BACKUP="$SETTINGS.bak-pre-starship"
if [ ! -e "$BACKUP" ]; then
  cp "$SETTINGS" "$BACKUP"
  say "Backed up settings to $BACKUP"
fi
say "Setting statusLine in $SETTINGS"
TMP=$(mktemp)
if [ "$JSON_TOOL" = jq ]; then
  jq --arg cmd "$STATUS_CMD" '.statusLine = {type: "command", command: $cmd}' "$SETTINGS" > "$TMP"
else
  python3 - "$SETTINGS" "$STATUS_CMD" > "$TMP" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
d["statusLine"] = {"type": "command", "command": sys.argv[2]}
print(json.dumps(d, indent=2))
PY
fi
mv "$TMP" "$SETTINGS"

# ── Smoke test ─────────────────────────────────────────────────────────────────
say "Smoke test with a sample payload"
NOW=$(date +%s)
printf '{"model":{"display_name":"Opus"},"effort":{"level":"high"},"context_window":{"used_percentage":42},"rate_limits":{"five_hour":{"used_percentage":30,"resets_at":%d},"seven_day":{"used_percentage":85,"resets_at":%d}}}' \
  $((NOW + 7400)) $((NOW + 300000)) \
  | sh -c "$STATUS_CMD"
echo

if command -v starship >/dev/null && starship prompt 2>&1 >/dev/null | grep -q WARN; then
  echo "note: your shell's starship prints warnings; check $BASE_CONFIG"
fi

say "Done. New Claude Code messages will use the new statusline."
echo "To go back to cship: cp '$BACKUP' '$SETTINGS'"
